import type { RecipeIngredient, ResearchResult } from "@/lib/types";
import { formatGrams, formatMl } from "@/lib/calc/units";

const qty = (i: RecipeIngredient) =>
  [i.grams != null ? formatGrams(i.grams) : null, i.ml != null ? formatMl(i.ml) : null, i.householdMeasure].filter(Boolean).join(" / ");

/** Plain-text/Markdown export with full source attribution. */
export function recipeToMarkdown(result: ResearchResult, ingredients: RecipeIngredient[] = result.recipe?.ingredients ?? []): string {
  const r = result.recipe;
  if (!r) return webToMarkdown(result);
  const o = r.overview;
  const groups = [...new Set(ingredients.map((i) => i.group))];
  const lines: string[] = [
    `# ${r.name}`,
    "",
    r.summary,
    "",
    `- Cake: ${o.cakeType}`,
    `- Finished weight: ~${o.finishedWeightGrams} g · Servings: ${o.servings}`,
    `- Difficulty: ${o.difficulty}`,
    `- Prep: ${o.prepMinutes} min · Bake: ${o.bakeMinutesMin}–${o.bakeMinutesMax} min · Total: ${o.totalMinutes} min`,
    `- Pan: ${o.panSize}${o.panCount > 1 ? ` × ${o.panCount}` : ""}`,
    `- Oven: ${o.ovenTempC}°C / ${o.ovenTempF}°F`,
    o.applianceNotes ? `- Appliance notes: ${o.applianceNotes}` : "",
    `- Texture: ${o.expectedTexture}`,
    "",
    "## Ingredients",
  ];
  for (const g of groups) {
    lines.push("", `### ${g}`);
    for (const i of ingredients.filter((x) => x.group === g)) lines.push(`- ${i.name} — ${qty(i)}${i.notes ? ` (${i.notes})` : ""}`);
  }
  lines.push("", "## Method");
  r.method.forEach((m, n) => lines.push(`${n + 1}. **${m.title}.** ${m.text}${m.why ? ` _Why: ${m.why}_` : ""}`));
  if (r.whyItWorks.length) {
    lines.push("", "## Why this recipe works");
    r.whyItWorks.forEach((w) => lines.push(`- **${w.topic}:** ${w.explanation}`));
  }
  if (r.frostingNotes) lines.push("", "## Frosting notes", r.frostingNotes);
  if (r.storage) lines.push("", "## Storage", r.storage);
  if (r.warnings.length) {
    lines.push("", "## Notes & caveats");
    r.warnings.forEach((w) => lines.push(`- ${w}`));
  }
  lines.push(
    "",
    "## Sources",
    "From the CakeRecipe Finder curated library — developed by comparing the techniques, ratios and methods used across these published recipes:",
    "",
  );
  for (const ref of result.references) {
    lines.push(`- ${ref.name} — ${ref.title}${ref.author ? ` by ${ref.author}` : ""}: ${ref.url}`);
  }
  lines.push(
    "",
    `Match confidence: ${result.confidence.level}`,
    "Generated by CakeRecipe Finder.",
  );
  return lines.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n");
}

export function downloadText(filename: string, text: string) {
  const blob = new Blob([text], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60) || "recipe";

function webToMarkdown(result: ResearchResult): string {
  const lines = [`# ${result.requirements.cakeType} — top-ranked published recipes`, "", "Found by CakeRecipe Finder web research. All recipes belong to their authors.", ""];
  for (const s of result.sources.filter((x) => x.role && x.role !== "not_used")) {
    lines.push(`## ${s.title} — ${s.sourceName}`, `${s.url}`, "");
    if (s.rating != null) lines.push(`Rating: ${s.rating}/5${s.reviewCount != null ? ` (${s.reviewCount} ratings)` : ""} · Score ${s.score}/100`, "");
    lines.push("Ingredients:", ...s.ingredients.map((i) => `- ${i}`), "", `Method: see ${s.url}`, "");
  }
  lines.push(`Researched ${new Date(result.researchedAt).toLocaleDateString()}`);
  return lines.join("\n");
}
